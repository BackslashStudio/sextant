namespace {
constexpr std::array<std::array<uint8_t, 4>, 256> build_viridis() {
    constexpr int kHead = 204;
    std::array<std::array<uint8_t, 4>, 256> lut{};
    for (int i = 0; i < kHead; ++i)
        for (int c = 0; c < 4; ++c) lut[i][c] = k_viridis_head[i][c];

    constexpr uint8_t end[4] = {253, 231, 37, 255};
    for (int i = kHead; i < 256; ++i) {
        const double t = static_cast<double>(i - (kHead - 1)) / static_cast<double>(255 - (kHead - 1));
        for (int c = 0; c < 4; ++c) {
            const double v = k_viridis_head[kHead - 1][c]
                            + t * (static_cast<double>(end[c]) - k_viridis_head[kHead - 1][c]);
            lut[i][c] = static_cast<uint8_t>(v + 0.5);
        }
    }
    return lut;
}

constexpr auto k_viridis = build_viridis();
} // namespace

